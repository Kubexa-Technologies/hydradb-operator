//! `gen-docs`: render one `docs/crd-<kind>.md` reference table per CRD kind.
//!
//! Every cell comes from the live CRD JSON schema produced by
//! [`kube::CustomResourceExt::crd`] (the same source `gen-crds`
//! serializes): field paths from flattened `properties` (nested objects
//! joined with `.`, array items suffixed with `[]`), required/optional from
//! each object's `required` array, defaults from each node's `default`,
//! descriptions from each node's `description`. A field the schema does not
//! describe gets an EMPTY description cell — filler prose is forbidden
//! (plan todo 33 failure scenario).

use std::path::{Path, PathBuf};

use hydradb_operator_api::crd::{GraphCluster, GraphIndexer, GraphNodePool};
use k8s_openapi::apiextensions_apiserver::pkg::apis::apiextensions::v1::CustomResourceDefinition;
use kube::CustomResourceExt;

/// Output directory (relative to the workspace root) receiving the tables.
const OUTPUT_DIR: &str = "docs";

/// Header carried by every generated reference: generated marker plus the exact
/// regeneration command. Mirrors the no-hand-edit discipline of
/// `gen-crds`/`gen-rbac`, in Markdown comment syntax (no timestamps, no
/// absolute paths, so reruns are byte-identical).
const HEADER: &str = "<!-- GENERATED by `cargo xtask gen-docs` — do not hand-edit. -->\n<!-- Regenerate with: cargo xtask gen-docs -->\n";

/// One flattened schema field: exactly one markdown table row.
struct FieldRow {
    path: String,
    type_name: String,
    required: bool,
    default: String,
    description: String,
}

/// Workspace root derived from this crate's manifest location.
///
/// `CARGO_MANIFEST_DIR` is `crates/xtask` both for the binary and for
/// integration tests, so two ancestors up is the workspace root regardless of
/// the process working directory.
fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .map(Path::to_path_buf)
        .unwrap_or_else(|| PathBuf::from("."))
}

/// Write `contents` to `path` only when the bytes differ (keeps runs idempotent
/// without churning mtimes).
fn write_if_different(path: &Path, contents: &str) -> anyhow::Result<()> {
    let current = std::fs::read_to_string(path).unwrap_or_default();
    if current != contents {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(path, contents)?;
    }
    Ok(())
}

/// Output filename for a kind: lowercase kind, e.g. `GraphCluster` →
/// `crd-graphcluster.md`.
fn doc_filename(kind: &str) -> String {
    format!("crd-{}.md", kind.to_lowercase())
}

/// Extract `(kind, group, version, openAPIV3Schema)` from a live CRD.
fn schema_of(
    crd: &CustomResourceDefinition,
) -> anyhow::Result<(String, String, String, serde_json::Value)> {
    let kind = crd.spec.names.kind.clone();
    let group = crd.spec.group.clone();
    let value = serde_json::to_value(crd)?;
    let Some(versions) = value
        .get("spec")
        .and_then(|spec| spec.get("versions"))
        .and_then(|versions| versions.as_array())
    else {
        anyhow::bail!("CRD {kind} has no spec.versions");
    };
    let Some(first) = versions.first() else {
        anyhow::bail!("CRD {kind} has an empty versions list");
    };
    let version = first
        .get("name")
        .and_then(|name| name.as_str())
        .unwrap_or_default()
        .to_owned();
    let Some(schema) = first
        .get("schema")
        .and_then(|schema| schema.get("openAPIV3Schema"))
        .cloned()
    else {
        anyhow::bail!("CRD {kind} has no openAPIV3Schema");
    };
    Ok((kind, group, version, schema))
}

/// Render a schema node's type cell from what the schema carries.
///
/// `x-kubernetes-int-or-string` nodes (e.g. `Quantity`-style divisors) carry
/// no `type`; the extension itself names the two inhabitant types, so the
/// cell names them rather than going empty.
fn schema_type(schema: &serde_json::Value) -> String {
    if let Some(marker) = schema.get("type").and_then(|kind| kind.as_str()) {
        return marker.to_owned();
    }
    if schema
        .get("x-kubernetes-int-or-string")
        .and_then(|flag| flag.as_bool())
        .unwrap_or(false)
    {
        return "integer or string".to_owned();
    }
    if schema.get("properties").is_some() {
        return "object".to_owned();
    }
    if schema.get("items").is_some() {
        return "array".to_owned();
    }
    String::new()
}

/// Make a cell safe for a markdown table: pipes would split the row, raw
/// newlines would split the table.
fn escape_cell(cell: &str) -> String {
    cell.replace('|', "\\|")
        .lines()
        .collect::<Vec<_>>()
        .join("<br/>")
}

/// Recurse into a field's children without extending the path: array `items`
/// (suffixed with `[]`) and combiner members (`anyOf`/`oneOf`/`allOf`, which
/// contribute `required` constraints, not fields).
fn descend(field: &serde_json::Value, path: &str, out: &mut Vec<FieldRow>) {
    collect_fields(field, path, out);
    match field.get("items") {
        Some(serde_json::Value::Array(members)) => {
            for member in members {
                collect_fields(member, &format!("{path}[]"), out);
            }
        }
        Some(items) => collect_fields(items, &format!("{path}[]"), out),
        None => {}
    }
    for combiner in ["anyOf", "oneOf", "allOf"] {
        if let Some(serde_json::Value::Array(members)) = field.get(combiner) {
            for member in members {
                collect_fields(member, path, out);
            }
        }
    }
}

/// Append one row per property of `node`, depth-first, keys sorted so reruns
/// are byte-identical. Open-ended maps (`additionalProperties`) contribute
/// only their own row: their keys are user data, not fields.
fn collect_fields(node: &serde_json::Value, prefix: &str, out: &mut Vec<FieldRow>) {
    let required: Vec<&str> = node
        .get("required")
        .and_then(|required| required.as_array())
        .map(|names| {
            names
                .iter()
                .filter_map(|name| name.as_str())
                .collect::<Vec<_>>()
        })
        .unwrap_or_default();
    let Some(properties) = node.get("properties").and_then(|props| props.as_object()) else {
        return;
    };
    let mut keys: Vec<&str> = properties.keys().map(String::as_str).collect();
    keys.sort_unstable();
    for key in keys {
        let Some(field) = properties.get(key) else {
            continue;
        };
        let path = if prefix.is_empty() {
            key.to_owned()
        } else {
            format!("{prefix}.{key}")
        };
        out.push(FieldRow {
            path: path.clone(),
            type_name: schema_type(field),
            required: required.contains(&key),
            default: field
                .get("default")
                .map(|default| serde_json::to_string(default).unwrap_or_default())
                .unwrap_or_default(),
            // No description in the schema means an EMPTY cell: never invent prose.
            description: field
                .get("description")
                .and_then(|text| text.as_str())
                .unwrap_or_default()
                .to_owned(),
        });
        descend(field, &path, out);
    }
}

/// Render the full markdown document for one kind.
fn render_doc(kind: &str, group: &str, version: &str, rows: &[FieldRow]) -> String {
    let mut doc = String::new();
    doc.push_str(HEADER);
    doc.push('\n');
    doc.push_str(&format!(
        "# {kind}\n\nAPI group `{group}`, version `{version}`.\n\n"
    ));
    doc.push_str("| Field | Type | Required | Default | Description |\n");
    doc.push_str("| --- | --- | --- | --- | --- |\n");
    for row in rows {
        let required = if row.required { "required" } else { "optional" };
        doc.push_str(&format!(
            "| {} | {} | {required} | {} | {} |\n",
            escape_cell(&row.path),
            escape_cell(&row.type_name),
            escape_cell(&row.default),
            escape_cell(&row.description),
        ));
    }
    doc
}

/// Generate one `docs/crd-<kind>.md` table per CRD kind, in stable kind order.
pub fn run() -> anyhow::Result<()> {
    let crds: Vec<CustomResourceDefinition> = vec![
        GraphCluster::crd(),
        GraphNodePool::crd(),
        GraphIndexer::crd(),
    ];
    let root = workspace_root();
    for crd in &crds {
        let (kind, group, version, schema) = schema_of(crd)?;
        let mut rows = Vec::new();
        collect_fields(&schema, "", &mut rows);
        if rows.is_empty() {
            anyhow::bail!("CRD {kind} flattened to zero fields");
        }
        let doc = render_doc(&kind, &group, &version, &rows);
        let filename = doc_filename(&kind);
        let path = root.join(OUTPUT_DIR).join(&filename);
        write_if_different(&path, &doc)?;
        println!(
            "wrote {OUTPUT_DIR}/{filename} (kind {kind}, {} fields)",
            rows.len()
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{collect_fields, escape_cell, render_doc, schema_type};
    use serde_json::json;

    /// Plan todo 33 failure scenario: a schema field without docs gains a row
    /// with an EMPTY description, never filler prose.
    #[test]
    fn undocumented_field_yields_empty_description_cell() {
        let schema = json!({
            "type": "object",
            "properties": {
                "spec": {
                    "type": "object",
                    "required": ["documented"],
                    "properties": {
                        "documented": {"type": "string", "description": "Has docs."},
                        "undocumented": {"type": "integer"}
                    }
                }
            }
        });
        let mut rows = Vec::new();
        collect_fields(&schema, "", &mut rows);
        assert_eq!(rows.len(), 3, "spec + two leaf fields");
        let undocumented = rows
            .iter()
            .find(|row| row.path == "spec.undocumented")
            .expect("undocumented field must still gain a row");
        assert_eq!(undocumented.description, "");
        assert!(!undocumented.required);
        let documented = rows
            .iter()
            .find(|row| row.path == "spec.documented")
            .expect("documented field must gain a row");
        assert_eq!(documented.description, "Has docs.");
        assert!(documented.required);
        let doc = render_doc("Kind", "group", "v1", &rows);
        assert!(
            doc.contains("| spec.undocumented | integer | optional |  |  |\n"),
            "empty default/description cells, no filler:\n{doc}"
        );
    }

    #[test]
    fn cells_escape_pipes_and_newlines() {
        assert_eq!(escape_cell("a|b"), "a\\|b");
        assert_eq!(escape_cell("one\ntwo"), "one<br/>two");
    }

    #[test]
    fn typeless_nodes_fall_back_to_schema_shape() {
        assert_eq!(
            schema_type(&json!({"x-kubernetes-int-or-string": true})),
            "integer or string"
        );
        assert_eq!(
            schema_type(&json!({"properties": {"a": {"type": "string"}}})),
            "object"
        );
        assert_eq!(schema_type(&json!({"items": {"type": "string"}})), "array");
        assert_eq!(schema_type(&json!({})), "");
    }
}
